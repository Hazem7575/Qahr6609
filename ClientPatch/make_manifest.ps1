# Rebuilds ClientPatch\manifest.txt (path, size, md5, reason) from ClientPatch\files.
# Run after changing anything in files\:  powershell -ExecutionPolicy Bypass -File make_manifest.ps1
# (the PatchServer builds its own manifest.json from the same folder at start or with the "rebuild" console command)
$ErrorActionPreference = 'Stop'
$files = Join-Path $PSScriptRoot 'files'
$out = Join-Path $PSScriptRoot 'manifest.txt'

function Reason([string]$p) {
    switch -Regex ($p) {
        '^Env_DX[89]/Conquer\.exe$'      { return 'REQUIRED-TO-CONNECT: patched TQ exe (stock exe + import of MeGaShield.dll); md5 must match GameServer bin\Debug\Files' }
        '^Env_DX[89]/MeGaShield\.dll$'   { return 'REQUIRED-TO-CONNECT: client shield + login key; md5 checked by GameServer _GShield' }
        '^Env_DX[89]/(GuardShield|HMProtect)\.dll$' { return 'REQUIRED-TO-CONNECT (caution): shield helper, may be loaded by the packed MeGaShield.dll' }
        '^Env_DX8/(EasyHook32|mscvr100d|D3DX8_56)\.dll$' { return 'REQUIRED-TO-CONNECT (caution): DX8 shield/runtime helper' }
        '^Env_DX[89]/Microsoft\.VC90'    { return 'REQUIRED-TO-CONNECT: VC90 runtime next to the exe (engine, no content)' }
        '^Env_DX[89]/'                   { return 'REQUIRED-TO-CONNECT: TQ engine DLL of the tested set (engine code, no textures/ini)' }
        '^config\.ini$'                  { return 'REQUIRED-TO-CONNECT: GameIP read by MeGaShield.dll' }
        '^Guard\.dat$'                   { return 'REQUIRED-TO-CONNECT: login-screen server list (name MeGa -> AccServer 26.31.69.47:9961); the launcher rewrites it from /servers' }
        '^GuardAr\.dat$'                 { return 'UNSURE: MeGa-era file next to Guard.dat, purpose unknown, new file (additive)' }
        '^Start_DX[89]\.bat$'            { return 'CONVENIENCE: start the game without the launcher (blacknull skips TQ autopatch)' }
        '^ini/globallotterycondition\.ini$' { return 'FEATURE Golden Tree: stock file is empty (Amount=0); generated by the server (ServerDataBase\Modules\GoldenTree\client\ini)' }
        '^ini/GUI\.ini$'                 { return 'FEATURE Dice + Golden Tree: stock GUI.ini with 4 lines changed ([579-1429] and [579-5481] x/y moved on-screen)' }
        default                          { return 'UNLISTED: add a reason in make_manifest.ps1' }
    }
}

$md5 = [Security.Cryptography.MD5]::Create()
$rows = New-Object System.Collections.Generic.List[string]
$rows.Add('# ClientPatch manifest - generated by make_manifest.ps1 ' + (Get-Date -Format 'yyyy-MM-dd HH:mm'))
$rows.Add('# path<TAB>size<TAB>md5<TAB>reason   (paths are relative to the client folder)')
$total = 0L
Get-ChildItem -Path $files -Recurse -File | Sort-Object FullName | ForEach-Object {
    $rel = $_.FullName.Substring($files.Length + 1).Replace('\', '/')
    if ($rel -ieq 'README.txt') { return }   # not distributed by the PatchServer
    $s = [IO.File]::OpenRead($_.FullName)
    try { $h = ([BitConverter]::ToString($md5.ComputeHash($s))).Replace('-', '').ToLowerInvariant() } finally { $s.Dispose() }
    $total += $_.Length
    $rows.Add("$rel`t$($_.Length)`t$h`t$(Reason $rel)")
}
$rows.Add("# total bytes: $total")
[IO.File]::WriteAllLines($out, $rows, (New-Object Text.UTF8Encoding($false)))
Write-Host "manifest.txt: $($rows.Count - 3) files, $total bytes"
